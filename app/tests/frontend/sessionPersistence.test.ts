import assert from 'node:assert/strict';
import test from 'node:test';
import { preferredTreasuryChain } from '../../src/lib/chain/preferredTreasuryChain.ts';
import { reportFooter } from '../../src/lib/reports/brandedPdf.ts';

test('a Solana treasury is preferred over the first chain row', () => {
  const base = {
    chainId: 8453,
    daoOnchainAddress: '0x1111111111111111111111111111111111111111',
    label: 'Base',
  };
  const solana = {
    chainId: null,
    daoOnchainAddress: 'So11111111111111111111111111111111111111112',
    label: 'Solana',
  };
  const picked = preferredTreasuryChain([base, solana], 'solana', base);
  assert.equal(picked.daoOnchainAddress, solana.daoOnchainAddress);
});

test('report footers carry Nave branding and the created date', () => {
  assert.equal(
    reportFooter('nave', 'October 26, 2026'),
    'Powered by Nave   ·   Generated by Nave   ·   Created on October 26, 2026',
  );
  assert.match(reportFooter('pay', 'October 26, 2026'), /Generated by Nave Pay/);
  assert.match(reportFooter('pay', 'October 26, 2026'), /Powered by Nave/);
});
