/**
 * Treasury-branded PDF reports.
 * The treasury name and logo lead. Nave stays in the footer.
 */

import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFImage, type PDFPage } from 'pdf-lib';

export type ReportProduct = 'nave' | 'pay';

export interface ReportTable {
  columns: string[];
  rows: string[][];
  /** Column weights. Defaults to equal widths. */
  weights?: number[];
}

export interface BrandedReport {
  product: ReportProduct;
  treasuryName: string;
  logoBytes?: Uint8Array | null;
  kicker: string;
  title: string;
  subtitle?: string;
  tables: ReportTable[];
  note?: string;
  createdOn?: Date;
}

const INK = rgb(17 / 255, 24 / 255, 39 / 255);
const MUTED = rgb(107 / 255, 114 / 255, 128 / 255);
const BRASS = rgb(185 / 255, 151 / 255, 79 / 255);
const PAPER = rgb(250 / 255, 248 / 255, 243 / 255);
const LINE = rgb(231 / 255, 226 / 255, 214 / 255);
const WHITE = rgb(1, 1, 1);

const PAGE_WIDTH = 612;
const PAGE_HEIGHT = 792;
const MARGIN = 48;

export function reportCreatedOn(date = new Date()): string {
  return date.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
}

export function reportFooter(product: ReportProduct, createdOn: string): string {
  const generated = product === 'pay' ? 'Generated by Nave Pay' : 'Generated by Nave';
  return `Powered by Nave   ·   ${generated}   ·   Created on ${createdOn}`;
}

export async function buildBrandedPdf(report: BrandedReport): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const display = await pdf.embedFont(StandardFonts.TimesRoman);
  const body = await pdf.embedFont(StandardFonts.Helvetica);
  const bodyBold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const logo = await embedLogo(pdf, report.logoBytes);
  const created = reportCreatedOn(report.createdOn ?? new Date());
  const footer = reportFooter(report.product, created);

  let page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
  let y = drawHeader(page, report, display, body, logo);

  for (const table of report.tables) {
    const drawn = drawTable(pdf, page, y, table, body, bodyBold, footer);
    page = drawn.page;
    y = drawn.y;
  }

  if (report.note) {
    if (y < 96) {
      drawFooter(page, footer, body);
      page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
      y = drawContinuation(page, report.treasuryName, body);
    }
    page.drawText(fit(report.note, body, 8.5, PAGE_WIDTH - MARGIN * 2), {
      x: MARGIN,
      y: y - 18,
      size: 8.5,
      font: body,
      color: MUTED,
    });
  }

  drawFooter(page, footer, body);
  pdf.setTitle(`${report.treasuryName} — ${report.title}`);
  pdf.setAuthor(report.product === 'pay' ? 'Nave Pay' : 'Nave');
  pdf.setCreator('Nave');
  return pdf.save();
}

export async function downloadBrandedPdf(filename: string, report: BrandedReport): Promise<void> {
  const bytes = await buildBrandedPdf(report);
  const blob = new Blob([Uint8Array.from(bytes)], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;
  link.click();
  window.setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export async function loadLogoBytes(url: string | null | undefined): Promise<Uint8Array | null> {
  const trimmed = url?.trim();
  if (!trimmed) return null;
  try {
    const response = await fetch(trimmed);
    if (!response.ok) return null;
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (bytes.length < 8) return null;
    const png = bytes[0] === 0x89 && bytes[1] === 0x50;
    const jpg = bytes[0] === 0xff && bytes[1] === 0xd8;
    return png || jpg ? bytes : null;
  } catch {
    return null;
  }
}

async function embedLogo(pdf: PDFDocument, bytes: Uint8Array | null | undefined): Promise<PDFImage | null> {
  if (!bytes || bytes.length < 8) return null;
  try {
    if (bytes[0] === 0x89 && bytes[1] === 0x50) return await pdf.embedPng(bytes);
    if (bytes[0] === 0xff && bytes[1] === 0xd8) return await pdf.embedJpg(bytes);
  } catch {
    return null;
  }
  return null;
}

function drawHeader(
  page: PDFPage,
  report: BrandedReport,
  display: PDFFont,
  body: PDFFont,
  logo: PDFImage | null,
): number {
  page.drawRectangle({ x: 0, y: 0, width: PAGE_WIDTH, height: PAGE_HEIGHT, color: PAPER });
  page.drawRectangle({ x: 0, y: PAGE_HEIGHT - 8, width: PAGE_WIDTH, height: 8, color: BRASS });

  let x = MARGIN;
  if (logo) {
    page.drawImage(logo, { x, y: PAGE_HEIGHT - 78, width: 36, height: 36 });
    x += 48;
  } else {
    const mark = initials(report.treasuryName);
    page.drawRectangle({ x, y: PAGE_HEIGHT - 78, width: 36, height: 36, color: INK });
    page.drawText(mark, {
      x: x + (36 - body.widthOfTextAtSize(mark, 11)) / 2,
      y: PAGE_HEIGHT - 64,
      size: 11,
      font: body,
      color: WHITE,
    });
    x += 48;
  }

  page.drawText(fit(report.treasuryName, display, 22, PAGE_WIDTH - x - MARGIN), {
    x,
    y: PAGE_HEIGHT - 58,
    size: 22,
    font: display,
    color: INK,
  });
  page.drawText(report.kicker.toUpperCase(), {
    x,
    y: PAGE_HEIGHT - 76,
    size: 8,
    font: body,
    color: BRASS,
  });

  page.drawText(fit(report.title, display, 16, PAGE_WIDTH - MARGIN * 2), {
    x: MARGIN,
    y: PAGE_HEIGHT - 112,
    size: 16,
    font: display,
    color: INK,
  });
  if (report.subtitle) {
    page.drawText(fit(report.subtitle, body, 10, PAGE_WIDTH - MARGIN * 2), {
      x: MARGIN,
      y: PAGE_HEIGHT - 128,
      size: 10,
      font: body,
      color: MUTED,
    });
    return PAGE_HEIGHT - 152;
  }
  return PAGE_HEIGHT - 136;
}

function drawContinuation(page: PDFPage, treasuryName: string, body: PDFFont): number {
  page.drawRectangle({ x: 0, y: 0, width: PAGE_WIDTH, height: PAGE_HEIGHT, color: PAPER });
  page.drawRectangle({ x: 0, y: PAGE_HEIGHT - 8, width: PAGE_WIDTH, height: 8, color: BRASS });
  page.drawText(fit(treasuryName, body, 10, PAGE_WIDTH - MARGIN * 2), {
    x: MARGIN,
    y: PAGE_HEIGHT - 32,
    size: 10,
    font: body,
    color: MUTED,
  });
  return PAGE_HEIGHT - 56;
}

function drawFooter(page: PDFPage, footer: string, body: PDFFont): void {
  page.drawLine({
    start: { x: MARGIN, y: 42 },
    end: { x: PAGE_WIDTH - MARGIN, y: 42 },
    thickness: 0.6,
    color: LINE,
  });
  page.drawText(fit(footer, body, 8, PAGE_WIDTH - MARGIN * 2), {
    x: MARGIN,
    y: 28,
    size: 8,
    font: body,
    color: MUTED,
  });
}

function drawTable(
  pdf: PDFDocument,
  startPage: PDFPage,
  startY: number,
  table: ReportTable,
  body: PDFFont,
  bodyBold: PDFFont,
  footer: string,
): { page: PDFPage; y: number } {
  const columns = table.columns.length > 0 ? table.columns : ['', ''];
  const weights = columns.map((_, index) => table.weights?.[index] ?? 1);
  const weightSum = weights.reduce((sum, weight) => sum + weight, 0) || 1;
  const width = PAGE_WIDTH - MARGIN * 2;
  const widths = weights.map((weight) => (width * weight) / weightSum);
  let page = startPage;
  let y = startY;

  const paintHeader = () => {
    let x = MARGIN;
    columns.forEach((column, index) => {
      page.drawText(fit(column, bodyBold, 8, widths[index] - 8), {
        x,
        y,
        size: 8,
        font: bodyBold,
        color: MUTED,
      });
      x += widths[index];
    });
    y -= 8;
    page.drawLine({
      start: { x: MARGIN, y },
      end: { x: PAGE_WIDTH - MARGIN, y },
      thickness: 0.8,
      color: INK,
    });
    y -= 16;
  };

  paintHeader();
  const rows = table.rows.length > 0 ? table.rows : [['—']];
  for (const row of rows) {
    if (y < 72) {
      drawFooter(page, footer, body);
      page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
      page.drawRectangle({ x: 0, y: 0, width: PAGE_WIDTH, height: PAGE_HEIGHT, color: PAPER });
      page.drawRectangle({ x: 0, y: PAGE_HEIGHT - 8, width: PAGE_WIDTH, height: 8, color: BRASS });
      y = PAGE_HEIGHT - 48;
      paintHeader();
    }
    let x = MARGIN;
    columns.forEach((_, index) => {
      const cell = row[index] ?? '';
      const numeric = index > 0 && /^-?\$?[\d,]+(\.\d+)?%?$/.test(cell.trim());
      const text = fit(cell, body, 9, widths[index] - 8);
      const textWidth = body.widthOfTextAtSize(text, 9);
      page.drawText(text, {
        x: numeric ? x + widths[index] - 8 - textWidth : x,
        y,
        size: 9,
        font: body,
        color: INK,
      });
      x += widths[index];
    });
    y -= 6;
    page.drawLine({
      start: { x: MARGIN, y },
      end: { x: PAGE_WIDTH - MARGIN, y },
      thickness: 0.4,
      color: LINE,
    });
    y -= 14;
  }
  return { page, y: y - 8 };
}

function initials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  const letters = (parts[0]?.[0] ?? 'N') + (parts[1]?.[0] ?? '');
  return letters.toUpperCase().slice(0, 2);
}

function fit(text: string, font: PDFFont, size: number, maxWidth: number): string {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (font.widthOfTextAtSize(clean, size) <= maxWidth) return clean;
  let kept = clean;
  while (kept.length > 1 && font.widthOfTextAtSize(`${kept}…`, size) > maxWidth) {
    kept = kept.slice(0, -1);
  }
  return `${kept}…`;
}
