/** Nave Pay subscription. $49 a month, paid in USDC cents. */

export const PAY_MONTHLY_CENTS = 4900;
export const PAY_GRACE_DAYS = 7;
export const PAY_DELETE_DAYS = 30;
export const PAY_TERMS = [1, 3, 12] as const;
export type PayTermMonths = (typeof PAY_TERMS)[number];

export const INVOICE_FOOTER = 'Generated by Nave Pay.';

export type SubscriptionState = 'none' | 'active' | 'grace' | 'locked' | 'purged';

export function isPayTerm(value: number): value is PayTermMonths {
  return value === 1 || value === 3 || value === 12;
}

/** 3 months are 10% off. 12 months are 25% off. */
export function subscriptionPriceCents(termMonths: PayTermMonths): number {
  const base = PAY_MONTHLY_CENTS * termMonths;
  if (termMonths === 3) return Math.round(base * 0.9);
  if (termMonths === 12) return Math.round(base * 0.75);
  return base;
}

export function subscriptionState(
  periodEndMs: number | null,
  nowMs: number,
  purged: boolean,
): SubscriptionState {
  if (purged) return 'purged';
  if (periodEndMs == null) return 'none';
  if (nowMs < periodEndMs) return 'active';
  const day = 24 * 60 * 60 * 1000;
  if (nowMs < periodEndMs + PAY_GRACE_DAYS * day) return 'grace';
  if (nowMs < periodEndMs + PAY_DELETE_DAYS * day) return 'locked';
  return 'purged';
}

export function subscriptionUsable(state: SubscriptionState): boolean {
  return state === 'active' || state === 'grace';
}

/** USD cents to token base units. USDC has 6 decimals, so $1.00 is 1_000_000. */
export function usdCentsToTokenUnits(cents: number, decimals: number): bigint {
  if (!Number.isInteger(cents) || cents < 0) throw new Error('invalid_cents');
  if (!Number.isInteger(decimals) || decimals < 2 || decimals > 18) throw new Error('invalid_decimals');
  return BigInt(cents) * 10n ** BigInt(decimals - 2);
}
