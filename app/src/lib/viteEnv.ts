export type ViteEnvKey = keyof typeof VITE_ENV;

/**
 * Read a `VITE_*` var by key via the static table above (no dynamic
 * `import.meta.env[key]`). Unknown keys — only reachable from untyped data
 * such as `strategyReadinessData.mjs` — resolve to `undefined`.
 */
export function readViteEnv(key: ViteEnvKey | string): string | undefined {
  const val = (VITE_ENV as Record<string, unknown>)[key];
  return typeof val === 'string' ? val : undefined;
}
